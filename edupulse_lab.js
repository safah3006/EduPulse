function logisticClassifier(X,y){
const {m,s}=stats(X),Z=X.map(r=>r.map((v,j)=>(v-m[j])/s[j])),w=new Array(X[0].length).fill(0);let b=0;
const sigmoid=z=>1/(1+Math.exp(-Math.max(-30,Math.min(30,z))));
for(let epoch=0;epoch<700;epoch++){let gb=0;const gw=new Array(w.length).fill(0);
for(let i=0;i<Z.length;i++){const p=sigmoid(b+Z[i].reduce((sum,v,j)=>sum+v*w[j],0)),err=p-y[i];gb+=err;for(let j=0;j<w.length;j++)gw[j]+=err*Z[i][j]}
const rate=.12/Z.length; b-=rate*gb;for(let j=0;j<w.length;j++)w[j]-=rate*(gw[j]+.001*w[j])}
return x=>sigmoid(b+x.reduce((sum,v,j)=>sum+((v-m[j])/s[j])*w[j],0))
}
function classificationTree(X,y,maxDepth,featureRng){
const grow=(idx,depth)=>{const positives=idx.reduce((sum,i)=>sum+y[i],0),p=positives/idx.length,leaf={p};
if(idx.length<4||p===0||p===1||(maxDepth&&depth>=maxDepth))return leaf;
let best=null;
for(const f of featureSample(X[0].length,featureRng)){const sorted=[...idx].sort((a,b)=>X[a][f]-X[b][f]);let leftPos=0;
for(let k=0;k<sorted.length-1;k++){leftPos+=y[sorted[k]];if(X[sorted[k]][f]===X[sorted[k+1]][f])continue;const nl=k+1,nr=idx.length-nl;if(nl<2||nr<2)continue;
const rightPos=positives-leftPos,score=nl-leftPos*leftPos/nl-(nl-leftPos)*(nl-leftPos)/nl+nr-rightPos*rightPos/nr-(nr-rightPos)*(nr-rightPos)/nr;
if(!best||score<best.score-1e-12)best={f,t:(X[sorted[k]][f]+X[sorted[k+1]][f])/2,score}}
}
if(!best)return leaf;
const left=idx.filter(i=>X[i][best.f]<=best.t),right=idx.filter(i=>X[i][best.f]>best.t);
if(!left.length||!right.length)return leaf;
return{f:best.f,t:best.t,l:grow(left,depth+1),r:grow(right,depth+1)}
};
const root=grow(X.map((_,i)=>i),0);
return x=>{let node=root;while(node.l)node=x[node.f]<=node.t?node.l:node.r;return node.p}
}
function classifyModels(X,y,o){
const {m,s}=stats(X),Z=X.map(r=>r.map((v,j)=>(v-m[j])/s[j]));
const knnProbability=x=>{const z=x.map((v,j)=>(v-m[j])/s[j]),neighbors=Z.map((r,i)=>[r.reduce((sum,v,j)=>sum+(v-z[j])**2,0),i]).sort((a,b)=>a[0]-b[0]).slice(0,Math.min(o.k,Z.length));return neighbors.reduce((sum,item)=>sum+y[item[1]],0)/neighbors.length};
const forest=()=>{const random=rng(o.seed),trees=[];for(let t=0;t<o.trees;t++){const boot=Array.from({length:X.length},()=>Math.floor(random()*X.length)),bx=boot.map(i=>X[i]),by=boot.map(i=>y[i]);trees.push(classificationTree(bx,by,o.depth,random))}
return x=>trees.reduce((sum,tree)=>sum+tree(x),0)/trees.length};
return[
{n:"Logistic Regression",s:"Logistic Regression",f:logisticClassifier(X,y)},
{n:"Decision Tree Classifier",s:"Decision Tree",f:classificationTree(X,y,o.depth)},
{n:"Random Forest Classifier",s:"Random Forest",f:forest()},
{n:"K-Nearest Neighbors",s:"KNN",f:knnProbability}
]}
function classificationMetrics(actual,probabilities){
let tp=0,tn=0,fp=0,fn=0;actual.forEach((label,i)=>{const predicted=probabilities[i]>=.5?1:0;if(label&&predicted)tp++;else if(!label&&!predicted)tn++;else if(predicted)fp++;else fn++});
const precision=tp+fp?tp/(tp+fp):0,recall=tp+fn?tp/(tp+fn):0;
return{accuracy:(tp+tn)/actual.length,precision,recall,f1:precision+recall?2*precision*recall/(precision+recall):0,tn,fp,fn,tp}
}
